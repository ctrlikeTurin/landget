// Database adapter with one async API over two backends:
//   - PostgreSQL (Supabase) when DATABASE_URL is set: production
//   - SQLite (better-sqlite3) otherwise: local dev and tests
// Queries use `?` placeholders and portable SQL; the pg backend rewrites them to $1..$n.
//
//   await db.all(sql, ...params)    -> rows
//   await db.get(sql, ...params)    -> first row or undefined
//   await db.run(sql, ...params)    -> { changes }
//   await db.insert(sql, ...params) -> new row id
//   await db.tx(async (q) => ...)   -> runs fn in a transaction; q has the same API
const path = require('path');
const fs = require('fs');

const PG = !!process.env.DATABASE_URL;

// Timestamps are stored as UTC text 'YYYY-MM-DD HH:MM:SS' on both backends.
const PG_NOW = "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')";

function schema(pg) {
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  const now = pg ? PG_NOW : 'CURRENT_TIMESTAMP';
  const ts = `TEXT NOT NULL DEFAULT (${now})`;
  return `
CREATE TABLE IF NOT EXISTS users (
  id ${id},
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  phone TEXT,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('lender','customer','admin')),
  suspended INTEGER NOT NULL DEFAULT 0,
  created_at ${ts}
);

CREATE TABLE IF NOT EXISTS listings (
  id ${id},
  owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  land_type TEXT NOT NULL,
  size ${real} NOT NULL,
  size_unit TEXT NOT NULL,
  size_acres ${real} NOT NULL,           -- normalised for filtering/sorting
  listing_types TEXT NOT NULL,           -- comma list: lease,sale,partnership
  price ${real} NOT NULL,
  currency TEXT NOT NULL DEFAULT 'KES',
  price_unit TEXT NOT NULL,              -- month, year, season, total
  negotiable INTEGER NOT NULL DEFAULT 0,
  duration_min ${real},
  duration_max ${real},
  duration_unit TEXT,                    -- months, years
  available_from TEXT,
  country TEXT NOT NULL,
  region TEXT NOT NULL DEFAULT '',
  town TEXT NOT NULL DEFAULT '',
  lat ${real},
  lng ${real},
  permitted_uses TEXT NOT NULL DEFAULT '[]',   -- JSON array
  prohibited_uses TEXT NOT NULL DEFAULT '[]',  -- JSON array
  uses_notes TEXT NOT NULL DEFAULT '',
  features TEXT NOT NULL DEFAULT '{}',         -- JSON object
  contact_phone TEXT, contact_whatsapp TEXT, contact_email TEXT,
  deed_number TEXT,
  deed_file TEXT,                        -- private object name
  id_file TEXT,                          -- private object name, never public
  show_deed INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','verified','rejected','paused')),
  reject_reason TEXT,
  duplicate_deed INTEGER NOT NULL DEFAULT 0,
  views INTEGER NOT NULL DEFAULT 0,
  created_at ${ts},
  updated_at ${ts}
);
CREATE INDEX IF NOT EXISTS idx_listings_status ON listings(status);
-- Deed numbers must be unique among verified listings.
CREATE UNIQUE INDEX IF NOT EXISTS idx_verified_deed ON listings(deed_number)
  WHERE status = 'verified' AND deed_number IS NOT NULL;

CREATE TABLE IF NOT EXISTS photos (
  id ${id},
  listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  filename TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS saves (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  created_at ${ts},
  PRIMARY KEY (user_id, listing_id)
);

-- One negotiation thread per (listing, customer).
CREATE TABLE IF NOT EXISTS threads (
  id ${id},
  listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  customer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  updated_at ${ts},
  UNIQUE (listing_id, customer_id)
);

CREATE TABLE IF NOT EXISTS offers (
  id ${id},
  thread_id INTEGER NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  from_user INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  price ${real} NOT NULL,
  duration TEXT,
  message TEXT,
  status TEXT NOT NULL DEFAULT 'offered' CHECK (status IN ('offered','countered','accepted','declined')),
  created_at ${ts}
);

CREATE TABLE IF NOT EXISTS messages (
  id ${id},
  thread_id INTEGER NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  from_user INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  offer_id INTEGER REFERENCES offers(id) ON DELETE SET NULL,
  created_at ${ts}
);

CREATE TABLE IF NOT EXISTS notifications (
  id ${id},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  link TEXT,
  read INTEGER NOT NULL DEFAULT 0,
  created_at ${ts}
);

CREATE TABLE IF NOT EXISTS reports (
  id ${id},
  listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  reporter_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')),
  created_at ${ts}
);

-- Owner's on-site GPS photo: where the phone was when the photo was taken.
CREATE TABLE IF NOT EXISTS site_checks (
  id ${id},
  listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  photo TEXT NOT NULL,                   -- private object name
  lat ${real} NOT NULL,
  lng ${real} NOT NULL,
  accuracy_m ${real} NOT NULL,
  created_at ${ts}
);
CREATE INDEX IF NOT EXISTS idx_site_checks_listing ON site_checks(listing_id);`;
}

// Columns added after the first release. Each entry is added if missing, on both backends.
const ADDED_COLUMNS = [
  // 0 = not verified, 1 = documents checked, 2 = title search confirmed, 3 = site visit confirmed
  ['listings', 'verification_level', 'INTEGER NOT NULL DEFAULT 0'],
  ['listings', 'title_search_ref', 'TEXT'],
  ['listings', 'site_visit_note', 'TEXT'],
];
// Listings verified before levels existed count as level 1 (documents checked).
const BACKFILL = "UPDATE listings SET verification_level = 1 WHERE status IN ('verified','paused') AND verification_level = 0";

function pgBackend() {
  const { Pool, types } = require('pg');
  types.setTypeParser(20, Number);   // COUNT(*) is bigint; ours always fit in a JS number
  types.setTypeParser(1700, Number); // numeric
  const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.DATABASE_SSL === 'false' ? false : { rejectUnauthorized: false },
    max: Number(process.env.DATABASE_POOL_MAX) || 5,
  });
  const toPg = (sql) => {
    let i = 0;
    return sql.replace(/\?/g, () => `$${++i}`).replace(/CURRENT_TIMESTAMP/g, PG_NOW);
  };
  const api = (runner) => ({
    all: async (sql, ...p) => (await runner.query(toPg(sql), p)).rows,
    get: async (sql, ...p) => (await runner.query(toPg(sql), p)).rows[0],
    run: async (sql, ...p) => ({ changes: (await runner.query(toPg(sql), p)).rowCount }),
    insert: async (sql, ...p) => (await runner.query(`${toPg(sql)} RETURNING id`, p)).rows[0].id,
  });
  return {
    ...api(pool),
    exec: (sql) => pool.query(sql),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(api(client));
        await client.query('COMMIT');
        return out;
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally { client.release(); }
    },
    // Supabase exposes the public schema over its REST API with a non-secret anon key.
    // RLS with no policies blocks that API entirely; the app connects as the table owner, which bypasses RLS.
    init: async () => {
      await pool.query(schema(true));
      for (const [t, col, type] of ADDED_COLUMNS) await pool.query(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${col} ${type}`);
      await pool.query(BACKFILL);
      await pool.query(['users', 'listings', 'photos', 'saves', 'threads', 'offers', 'messages', 'notifications', 'reports', 'site_checks']
        .map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n'));
    },
    close: () => pool.end(),
  };
}

function sqliteBackend() {
  const Database = require('better-sqlite3');
  const file = process.env.DB_PATH || path.join(__dirname, '..', 'data', 'landlink.db');
  if (file !== ':memory:') fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  const sdb = new Database(file);
  sdb.pragma('journal_mode = WAL');
  sdb.pragma('foreign_keys = ON');
  const cache = new Map();
  const stmt = (sql) => { if (!cache.has(sql)) cache.set(sql, sdb.prepare(sql)); return cache.get(sql); };
  const q = {
    all: async (sql, ...p) => stmt(sql).all(...p),
    get: async (sql, ...p) => stmt(sql).get(...p),
    run: async (sql, ...p) => ({ changes: stmt(sql).run(...p).changes }),
    insert: async (sql, ...p) => Number(stmt(sql).run(...p).lastInsertRowid),
  };
  // Async callbacks can't use better-sqlite3's sync transaction(), so use BEGIN/COMMIT.
  // Fine for dev/tests; production runs on Postgres with a dedicated client per tx.
  let chain = Promise.resolve();
  return {
    ...q,
    exec: async (sql) => sdb.exec(sql),
    tx(fn) {
      const run = chain.then(async () => {
        sdb.exec('BEGIN');
        try { const out = await fn(q); sdb.exec('COMMIT'); return out; } catch (e) { sdb.exec('ROLLBACK'); throw e; }
      });
      chain = run.catch(() => {});
      return run;
    },
    init: async () => {
      sdb.exec(schema(false));
      for (const [t, col, type] of ADDED_COLUMNS) {
        if (!sdb.prepare(`PRAGMA table_info(${t})`).all().some((c) => c.name === col)) sdb.exec(`ALTER TABLE ${t} ADD COLUMN ${col} ${type}`);
      }
      sdb.exec(BACKFILL);
    },
    close: async () => sdb.close(),
  };
}

const db = PG ? pgBackend() : sqliteBackend();
db.kind = PG ? 'postgres' : 'sqlite';
// Callers await this before serving or querying.
db.ready = db.init();
module.exports = db;
